def current_lang() -> str:
    return app_settings.get("language") or DEFAULT

def t(key: str, **fmt) -> str:
    lang = current_lang()
    s = _STRINGS.get(lang, _STRINGS[DEFAULT]).get(key)
    if s is None:
        s = _STRINGS[DEFAULT].get(key, key)
    if fmt:
        try:
            return s.format(**fmt)
        except (KeyError, IndexError):
            return s
    return s

def toggle_label(key: str) -> str:
    lang = current_lang()
    return _TOGGLE_LABELS.get(lang, _TOGGLE_LABELS[DEFAULT]).get(
        key, _TOGGLE_LABELS[DEFAULT].get(key, key)
    )
